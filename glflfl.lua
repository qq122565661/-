local EnableTranslate = false
local originTextCache = {}
local dictList = {}
for eng,chn in pairs(TranslateDict) do
    table.insert(dictList,{eng=eng,chn=chn})
end
table.sort(dictList,function(a,b) return #a.eng > #b.eng end)

local function TranslateText(text)
    if not text or type(text)~="string" or text=="" then return text end
    return TranslateDict[text] or text
end

local function ScanAndTranslate()
    local guiList = {LocalPlayer:FindFirstChild("PlayerGui"), game:GetService("CoreGui")}
    for _,guiRoot in ipairs(guiList) do
        if not guiRoot then continue end
        local ok,err = pcall(function()
            for _,obj in ipairs(guiRoot:GetDescendants()) do
                if obj:IsA("TextLabel") or obj:IsA("TextButton") or obj:IsA("TextBox") then
                    local uid = obj:GetDebugId()..tostring(obj)
                    if not originTextCache[uid] then
                        originTextCache[uid] = obj.Text
                    end
                    if EnableTranslate then
                        local newText = TranslateText(obj.Text)
                        obj.Text = newText
                    else
                        obj.Text = originTextCache[uid]
                    end
                end
            end
        end)
        if not ok then
            warn("翻译扫描异常：",err)
        end
    end
end

task.spawn(function()
    while task.wait(0.3) do
        ScanAndTranslate()
    end
end)

