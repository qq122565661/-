local cache = {}

local function TranslateText(text)
    if not text or type(text)~="string" then return text end
    if cache[text] then return cache[text] end
    local res = text
    local list = {}
    for eng,chn in pairs(TranslateDict) do
        table.insert(list,{eng=eng,chn=chn})
    end
    -- 长词条优先匹配，避免短词破坏长文本
    table.sort(list,function(a,b) return #a.eng > #b.eng end)
    for _,item in ipairs(list) do
        res = res:gsub("%f[%a]"..item.eng.."%f[%A]",item.chn)
    end
    cache[text] = res
    return res
end

local function ScanAndTranslate()
    local guiList = {LocalPlayer:FindFirstChild("PlayerGui"), game:GetService("CoreGui")}
    for _,guiRoot in ipairs(guiList) do
        if not guiRoot then continue end
        for _,obj in ipairs(guiRoot:GetDescendants()) do
            if obj:IsA("TextLabel") or obj:IsA("TextButton") or obj:IsA("TextBox") then
                local newText = TranslateText(obj.Text)
                if newText ~= obj.Text then
                    obj.Text = newText
                end
            end
        end
